local function padded(text, callback)
  local before, content, after = text:match("^(%s*)(.-)(%s*)$")
  return before .. callback(content) .. after
end

function M.translate(text, locale, domain, overrides)
  if type(text) ~= "string" then
    return text
  end
  local entries = domains[domain] or {}
  if locale == "en" then
    -- The user's pre-existing dashboard already contains Chinese labels.
    -- Reverse only its known UI phrases; never reverse user content elsewhere.
    if domain == "dashboard" then
      return padded(text, function(content)
        for english, chinese in pairs(entries) do
          if content == chinese then
            return english
          end
        end
        return content
      end)
    end
    return text
  end
  local custom = overrides and overrides[domain] or {}
  if custom[text] or entries[text] then
    return custom[text] or entries[text]
  end
  return padded(text, function(content)
    if custom[content] or entries[content] then
      return custom[content] or entries[content]
    end
    if domain == "keymaps" then
      local base, scope = content:match("^(.-) %(([^()]+)%)$")
      local scopes = { ["root dir"] = "项目根目录", ["Root Dir"] = "项目根目录", cwd = "当前目录" }
      if base and scopes[scope] then
        return M.translate(base, locale, domain, overrides) .. "（" .. scopes[scope] .. "）"
      end
      local count = content:match("^(%d+) keymaps?$")
      if count then
        return count .. " 个快捷键"
      end
      for _, prefix in ipairs({ "Toggle ", "Enable ", "Disable " }) do
        if content:sub(1, #prefix) == prefix then
          local rest = content:sub(#prefix + 1)
          if entries[rest] or custom[rest] then
            local action = ({ ["Toggle "] = "切换", ["Enable "] = "启用", ["Disable "] = "禁用" })[prefix]
            return action .. (custom[rest] or entries[rest])
          end
        end
      end
    elseif domain == "lazy" then
      local label, key = content:match("^(%a+) %((.-)%)$")
      if label and entries[label] then
        return entries[label] .. " (" .. key .. ")"
      end
      local count = content:match("^(%d+) plugins$")
      if count then
        return count .. " 个插件"
      end
      local version = content:match("^version (.+) is available$")
      if version then
        return "可更新至 " .. version
      end
      local updated = content:match("^updated to (.+)$")
      if updated then
        return "已更新至 " .. updated
      end
      local from, to = content:match("^updated from (%x+) to (%x+)$")
      if from then
        return "已从 " .. from .. " 更新至 " .. to
      end
    end
    return content
  end)
end

return M
